import { AsyncLocalStorage } from "node:async_hooks";
import type { Pool, PoolClient, QueryResult, QueryResultRow } from "pg";

export type AnalysisLeaseGuard = { jobId: string; expectedLeaseOwner: string; expectedAttempts: number };

/** One transaction context for research rows, queue state, and version registration. */
export class AnalysisPgContext {
  private readonly scope = new AsyncLocalStorage<PoolClient>();
  private readonly leaseScope = new AsyncLocalStorage<AnalysisLeaseGuard>();

  constructor(readonly pool: Pool) {}

  get client(): Pool | PoolClient { return this.scope.getStore() ?? this.pool; }
  get leaseGuard(): AnalysisLeaseGuard | undefined { return this.leaseScope.getStore(); }

  runWithJobLease<T>(jobId: string, workerId: string, attempts: number,
    operation: () => Promise<T>): Promise<T> {
    return this.leaseScope.run({ jobId, expectedLeaseOwner: workerId, expectedAttempts: attempts }, operation);
  }

  /** Call inside a short transaction immediately before each job-owned mutation. */
  async assertLease(explicit?: AnalysisLeaseGuard, runId?: string): Promise<void> {
    const guard = explicit ?? this.leaseGuard;
    if (!guard) return;
    if (!this.scope.getStore()) throw new Error("Lease check requires a transaction");
    const result = await this.query<{ id: string }>(`SELECT id FROM analysis_research_jobs
      WHERE id=$1 AND lease_owner=$2 AND attempts=$3 AND status IN ('leased','running')
        AND lease_expires_at::timestamptz > now()
        AND ($4::text IS NULL OR run_id=$4) FOR UPDATE`,
    [guard.jobId, guard.expectedLeaseOwner, guard.expectedAttempts, runId ?? null]);
    if (!result.rows[0]) throw new Error("STALE_RESEARCH_LEASE");
  }

  query<T extends QueryResultRow = QueryResultRow>(sql: string, values: unknown[] = []): Promise<QueryResult<T>> {
    return this.client.query<T>(sql, values);
  }

  async transaction<T>(operation: () => Promise<T> | T): Promise<T> {
    if (this.scope.getStore()) return operation();
    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");
      const result = await this.scope.run(client, operation);
      await client.query("COMMIT");
      return result;
    } catch (error) {
      await client.query("ROLLBACK");
      throw error;
    } finally { client.release(); }
  }

  /** Repeatable DDL; the caller owns the pool and also migrates the shared RunStore. */
  async migrate(): Promise<void> {
    await this.transaction(async () => {
      await this.query("SELECT pg_advisory_xact_lock(4832941, 41)");
      await this.query(`
        CREATE TABLE IF NOT EXISTS analysis_creator_runs (
          id text PRIMARY KEY, profile_url text NOT NULL, status text NOT NULL,
          current_stage text NOT NULL, creator_id text, created_at text NOT NULL,
          updated_at text NOT NULL, run_json jsonb NOT NULL
        );
        CREATE INDEX IF NOT EXISTS analysis_creator_runs_updated ON analysis_creator_runs(updated_at DESC,id DESC);
        CREATE INDEX IF NOT EXISTS analysis_creator_runs_profile ON analysis_creator_runs(profile_url,updated_at DESC);
        CREATE TABLE IF NOT EXISTS analysis_research_jobs (
          id text PRIMARY KEY, run_id text NOT NULL REFERENCES analysis_creator_runs(id),
          node_key text NOT NULL, status text NOT NULL, idempotency_key text NOT NULL UNIQUE,
          attempts integer NOT NULL DEFAULT 0, max_attempts integer NOT NULL,
          available_at text NOT NULL, lease_owner text, lease_expires_at text, heartbeat_at text,
          payload_json jsonb NOT NULL, last_error text, created_at text NOT NULL, updated_at text NOT NULL
        );
        CREATE INDEX IF NOT EXISTS analysis_research_jobs_claim ON analysis_research_jobs(status,available_at,created_at);
        CREATE INDEX IF NOT EXISTS analysis_research_jobs_run ON analysis_research_jobs(run_id,created_at DESC);
        CREATE TABLE IF NOT EXISTS analysis_import_receipts (
          source_id text PRIMARY KEY, workspace_id text NOT NULL, imported_at text NOT NULL,
          source_hint text NOT NULL, manifest jsonb NOT NULL,
          state text NOT NULL DEFAULT 'importing' CHECK (state IN ('importing','completed')),
          completed_at text
        );
        ALTER TABLE analysis_import_receipts ADD COLUMN IF NOT EXISTS state text NOT NULL DEFAULT 'importing';
        ALTER TABLE analysis_import_receipts ADD COLUMN IF NOT EXISTS completed_at text;
        CREATE TABLE IF NOT EXISTS analysis_imported_jobs (
          job_id text PRIMARY KEY REFERENCES analysis_research_jobs(id), source_id text NOT NULL
            REFERENCES analysis_import_receipts(source_id)
        );
        CREATE TABLE IF NOT EXISTS analysis_research_events (
          sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          run_id text NOT NULL REFERENCES analysis_creator_runs(id), job_id text,
          type text NOT NULL, created_at text NOT NULL, message text NOT NULL, payload_json jsonb NOT NULL
        );
        CREATE INDEX IF NOT EXISTS analysis_research_events_run ON analysis_research_events(run_id,sequence);
        CREATE TABLE IF NOT EXISTS analysis_creator_batches (
          id text PRIMARY KEY, schema_version text NOT NULL, name text NOT NULL,
          created_at text NOT NULL, operation_key text NOT NULL UNIQUE, command_hash text NOT NULL
        );
        CREATE INDEX IF NOT EXISTS analysis_creator_batches_created ON analysis_creator_batches(created_at DESC,id DESC);
        CREATE TABLE IF NOT EXISTS analysis_creator_batch_items (
          batch_id text NOT NULL REFERENCES analysis_creator_batches(id) ON DELETE CASCADE,
          position integer NOT NULL, run_id text NOT NULL,
          PRIMARY KEY(batch_id,position),UNIQUE(batch_id,run_id)
        );
        CREATE INDEX IF NOT EXISTS analysis_creator_batch_items_run ON analysis_creator_batch_items(run_id);
        CREATE TABLE IF NOT EXISTS analysis_workflow_executions (
          id text PRIMARY KEY, creator_run_id text NOT NULL REFERENCES analysis_creator_runs(id),
          parent_workflow_run_id text, parent_step_run_id text UNIQUE,
          document jsonb NOT NULL
        );
        CREATE INDEX IF NOT EXISTS analysis_workflow_executions_creator ON analysis_workflow_executions(creator_run_id);
        CREATE INDEX IF NOT EXISTS analysis_workflow_executions_parent ON analysis_workflow_executions(parent_workflow_run_id);
        CREATE TABLE IF NOT EXISTS analysis_artifact_refs (
          reference text PRIMARY KEY, run_id text NOT NULL, logical_name text NOT NULL,
          blob_key text NOT NULL, sha256 text NOT NULL, bytes bigint NOT NULL,
          chunk_keys jsonb NOT NULL DEFAULT '[]'::jsonb,
          dependencies jsonb NOT NULL DEFAULT '[]'::jsonb, created_at text NOT NULL
        );
        CREATE INDEX IF NOT EXISTS analysis_artifact_refs_run ON analysis_artifact_refs(run_id);
        ALTER TABLE analysis_artifact_refs ADD COLUMN IF NOT EXISTS chunk_keys jsonb NOT NULL DEFAULT '[]'::jsonb;
        CREATE TABLE IF NOT EXISTS analysis_media_refs (
          reference text PRIMARY KEY, run_id text NOT NULL, managed_path text NOT NULL,
          sha256 text NOT NULL, bytes bigint NOT NULL, created_at text NOT NULL
        );
        CREATE INDEX IF NOT EXISTS analysis_media_refs_run ON analysis_media_refs(run_id);
      `);
    });
  }
}
